
import os

from dotenv import load_dotenv
from fastapi_mail import ConnectionConfig, FastMail, MessageSchema, MessageType

load_dotenv()

smtp_email = os.getenv("SMTP_EMAIL")
smtp_password = os.getenv("SMTP_APP_PASSWORD")

if not smtp_email or not smtp_password:
    raise RuntimeError("SMTP_EMAIL or SMTP_APP_PASSWORD is missing from .env")

conf = ConnectionConfig(
    MAIL_USERNAME=smtp_email,
    MAIL_PASSWORD=smtp_password,
    MAIL_FROM=smtp_email,
    MAIL_PORT=465,
    MAIL_SERVER="smtp.gmail.com",
    MAIL_STARTTLS=False,
    MAIL_SSL_TLS=True,
    USE_CREDENTIALS=True,
    VALIDATE_CERTS=True,
)


async def send_password_reset_email(to_email: str, reset_link: str):
    message = MessageSchema(
        subject="SafeRoute Password Reset",
        recipients=[to_email],
        body=f"""
        <h2>Reset your SafeRoute password</h2>
        <p>We received a request to reset your password.</p>
        <p>
            <a href="{reset_link}">Reset my password</a>
        </p>
        <p>This link is time-limited and can only be used once.</p>
        <p>If you did not request this, you can ignore this email.</p>
        """,
        subtype=MessageType.html,
    )

    mailer = FastMail(conf)
    await mailer.send_message(message)


